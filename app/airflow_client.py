"""Minimal Airflow 3 REST client (``/api/v2``, JWT from ``/auth/token``).

Works with the SimpleAuthManager used by ``airflow standalone``. Credentials come from
``HGRAG_AIRFLOW_USER`` / ``HGRAG_AIRFLOW_PASSWORD`` or, by default, from the password file
generated by ``orchestration/run_airflow.sh`` (``orchestration/.airflow``).
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import requests

PROJECT_ROOT = Path(os.environ.get("HGRAG_PROJECT_ROOT", Path(__file__).resolve().parents[1]))
BASE_URL = os.environ.get("HGRAG_AIRFLOW_URL", "http://localhost:8080").rstrip("/")
PASSWORD_FILE = Path(os.environ.get(
    "HGRAG_AIRFLOW_PASSWORD_FILE",
    PROJECT_ROOT / "orchestration" / ".airflow" / "simple_auth_manager_passwords.json.generated",
))

# Display order when one task has several mapped instances: the "worst" state wins.
STATE_PRIORITY = [
    "failed", "upstream_failed", "up_for_retry", "restarting", "running", "deferred",
    "queued", "scheduled", "up_for_reschedule", "removed", "skipped", "success",
]
STATE_COLORS = {
    "success": "#2e9e5b", "running": "#74c365", "failed": "#d64545", "upstream_failed": "#e8a33d",
    "up_for_retry": "#f2c94c", "queued": "#8e8e93", "scheduled": "#b9b9be", "skipped": "#ff9fc0",
    "deferred": "#9b6dd6", "restarting": "#a98274", "removed": "#d8d8d8", "none": "#ffffff",
}


class AirflowError(RuntimeError):
    pass


def _credentials() -> tuple[str, str]:
    user, pwd = os.environ.get("HGRAG_AIRFLOW_USER"), os.environ.get("HGRAG_AIRFLOW_PASSWORD")
    if user and pwd:
        return user, pwd
    if PASSWORD_FILE.exists():
        passwords = json.loads(PASSWORD_FILE.read_text(encoding="utf-8"))
        user = user or ("admin" if "admin" in passwords else next(iter(passwords)))
        return user, passwords[user]
    raise AirflowError(
        "No Airflow credentials: set HGRAG_AIRFLOW_USER / HGRAG_AIRFLOW_PASSWORD "
        f"(or start Airflow so that {PASSWORD_FILE} exists)."
    )


class AirflowClient:
    def __init__(self, base_url: str = BASE_URL, timeout: float = 15.0):
        self.base_url, self.timeout = base_url, timeout
        self._token: str | None = None

    def _login(self) -> str:
        user, pwd = _credentials()
        r = requests.post(f"{self.base_url}/auth/token", json={"username": user, "password": pwd},
                          timeout=self.timeout)
        if r.status_code >= 400:
            raise AirflowError(f"Airflow login failed ({r.status_code}): {r.text[:200]}")
        self._token = r.json()["access_token"]
        return self._token

    def _request(self, method: str, path: str, **kwargs: Any) -> Any:
        for attempt in (0, 1):
            token = self._token or self._login()
            try:
                r = requests.request(method, f"{self.base_url}/api/v2{path}", timeout=self.timeout,
                                     headers={"Authorization": f"Bearer {token}"}, **kwargs)
            except requests.ConnectionError as exc:
                raise AirflowError(f"Airflow unreachable at {self.base_url} (is it running?)") from exc
            if r.status_code == 401 and attempt == 0:  # expired token
                self._token = None
                continue
            if r.status_code >= 400:
                raise AirflowError(f"{method} {path} -> {r.status_code}: {r.text[:300]}")
            return r.json()
        raise AirflowError("unreachable")

    # -- reads ---------------------------------------------------------------
    def version(self) -> str:
        """Liveness check: also tells when something else than Airflow answers on the port."""
        try:
            r = requests.get(f"{self.base_url}/api/v2/version", timeout=self.timeout)
        except requests.ConnectionError as exc:
            raise AirflowError(f"Nothing listens on {self.base_url}") from exc
        if r.status_code != 200 or "version" not in r.text:
            raise AirflowError(
                f"{self.base_url}/api/v2/version answered {r.status_code}: this does not look like "
                "Airflow (another program may use this port: try another port, see README)."
            )
        return r.json()["version"]

    def health(self) -> dict[str, Any]:
        r = requests.get(f"{self.base_url}/api/v2/monitor/health", timeout=self.timeout)
        r.raise_for_status()
        return r.json()

    def dag(self, dag_id: str) -> dict[str, Any]:
        return self._request("GET", f"/dags/{dag_id}")

    def tasks(self, dag_id: str) -> list[dict[str, Any]]:
        return self._request("GET", f"/dags/{dag_id}/tasks")["tasks"]

    def runs(self, dag_id: str, limit: int = 10) -> list[dict[str, Any]]:
        data = self._request("GET", f"/dags/{dag_id}/dagRuns",
                             params={"limit": limit, "order_by": "-run_after"})
        return data["dag_runs"]

    def task_instances(self, dag_id: str, run_id: str) -> list[dict[str, Any]]:
        data = self._request("GET", f"/dags/{dag_id}/dagRuns/{run_id}/taskInstances",
                             params={"limit": 1000})
        return data["task_instances"]

    def task_log(self, dag_id: str, run_id: str, task_id: str, try_number: int = 1,
                 map_index: int = -1) -> str:
        return self._log(dag_id, run_id, task_id, try_number, map_index)

    def _log(self, dag_id: str, run_id: str, task_id: str, try_number: int, map_index: int) -> str:
        data = self._request(
            "GET", f"/dags/{dag_id}/dagRuns/{run_id}/taskInstances/{task_id}/logs/{try_number}",
            params={"map_index": map_index, "full_content": "true"},
        )
        content = data.get("content", data)
        lines = []
        for item in content if isinstance(content, list) else [content]:
            lines.append(item if isinstance(item, str) else item.get("event", json.dumps(item)))
        return "\n".join(lines)

    # -- writes --------------------------------------------------------------
    def trigger(self, dag_id: str, conf: dict[str, Any] | None = None) -> dict[str, Any]:
        """Create a DAG run now (``logical_date`` null = manual run, no data interval)."""
        return self._request("POST", f"/dags/{dag_id}/dagRuns",
                             json={"logical_date": None, "conf": conf or {}})


def aggregate_states(tasks: list[dict[str, Any]], instances: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """Per task_id: worst state, mapped counters and total duration (mapped instances merged)."""
    by_task: dict[str, list[dict[str, Any]]] = {}
    for ti in instances:
        by_task.setdefault(ti["task_id"], []).append(ti)
    out: dict[str, dict[str, Any]] = {}
    for t in tasks:
        tis = by_task.get(t["task_id"], [])
        states = [ti.get("state") or "none" for ti in tis]
        state = "none"
        for s in STATE_PRIORITY:
            if s in states:
                state = s
                break
        mapped = len(tis) > 1 or any(ti.get("map_index", -1) >= 0 for ti in tis)
        out[t["task_id"]] = {
            "state": state,
            "mapped": mapped or bool(t.get("is_mapped")),
            "n": len(tis),
            "n_success": states.count("success"),
            "duration": sum(ti.get("duration") or 0 for ti in tis),
            "instances": tis,
        }
    return out


def dag_to_dot(tasks: list[dict[str, Any]], status: dict[str, dict[str, Any]]) -> str:
    """Graphviz DOT of the task graph, nodes coloured by state."""
    lines = ['digraph G {', 'rankdir=LR; bgcolor="transparent";',
             'node [shape=box, style="rounded,filled", fontname="Helvetica", fontcolor="white"];']
    for t in tasks:
        st = status.get(t["task_id"], {"state": "none", "mapped": False, "n": 0, "n_success": 0})
        color = STATE_COLORS.get(st["state"], "#8e8e93")
        font = "black" if st["state"] in ("none", "scheduled", "up_for_retry", "removed") else "white"
        label = t["task_id"] + (f"\\n[{st['n_success']}/{st['n']}]" if st["mapped"] else "")
        label += f"\\n{st['state']}"
        lines.append(f'"{t["task_id"]}" [label="{label}", fillcolor="{color}", fontcolor="{font}"];')
    for t in tasks:
        for d in t.get("downstream_task_ids", []):
            lines.append(f'"{t["task_id"]}" -> "{d}";')
    lines.append("}")
    return "\n".join(lines)
